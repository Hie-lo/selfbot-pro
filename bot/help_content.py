def resolve_section(name: str) -> str | None:
    """تبدیل ورودی کاربر (فارسی/کلید) به کلید بخش"""
    name = (name or "").strip().lower().replace("\u200c", "")
    if not name:
        return None
    if name in SECTIONS:
        return name
    normalized = {k.replace("\u200c", ""): v for k, v in ALIASES.items()}
    if name in normalized:
        return normalized[name]
    for alias, key in normalized.items():
        if alias in name or name in alias:
            return key
    return None


def section_text(key: str) -> str:
    if key == "main":
        return MAIN_TEXT
    sec = SECTIONS.get(key)
    return sec["text"] if sec else MAIN_TEXT


def layout_for(key: str) -> tuple[list[list[str]], str | None]:
    """
    دکمه‌های یک صفحه: (ردیف‌های کلید بخش‌ها، کلید صفحه‌ی بازگشت یا None)
    """
    if key == "main":
        return MAIN_LAYOUT, None
    sec = SECTIONS.get(key)
    if not sec:
        return MAIN_LAYOUT, None
    return CHILDREN.get(key, []), sec.get("parent", "main")


def section_title(key: str) -> str:
    if key == "main":
        return "🏠 صفحه اصلی راهنما"
    return SECTIONS.get(key, {}).get("title", key)


def text_index() -> str:
    """نسخه‌ی متنی صفحه اصلی (وقتی دکمه‌ی شیشه‌ای در دسترس نیست)"""
    alias_by_key: dict[str, str] = {}
    for alias, key in ALIASES.items():
        alias_by_key.setdefault(key, alias)
    lines = [MAIN_TEXT, "", "<b>بخش‌ها:</b>"]
    for row in MAIN_LAYOUT:
        for key in row:
            lines.append(
                f"{SECTIONS[key]['title']} → <code>.راهنما {alias_by_key.get(key, key)}</code>"
            )
            for sub_row in CHILDREN.get(key, []):
                for sub in sub_row:
                    lines.append(
                        f"   ↳ {SECTIONS[sub]['title']} → "
                        f"<code>.راهنما {alias_by_key.get(sub, sub)}</code>"
                    )
    return "\n".join(lines)
